FOCUS_LINKS=()       # "project|target_path" pairs -- mirrors QUESTIONS_LINKS

for conf in "${CONF_FILES[@]}"; do
  # Reset every field this format understands so a conf file missing a
  # var can't silently inherit the previous file's value.
  unset PROJECT SWEEP_JOB_NAME SWEEP_SCRIPT SWEEP_CRON
  unset BATCH_JOB_NAME BATCH_SCRIPT BATCH_CRON PROJECT_REPO_PATH
  # Runtime fields (read by scheduler-run) that also gate command resolution
  # here -- reset so one conf's value can't leak into the next.
  unset REPO_URL SWEEP_PROMPT BATCH_PROMPT SCHEDULER_SUBDIR
  # Scoping axes -- reset so one conf's account/host can't leak into the next.
  unset CRON_ACCOUNT CRON_HOST
  # shellcheck disable=SC1090
  source "$conf"

  name=$(basename "$conf" .conf)
  PROJECT="${PROJECT:-$name}"

  # Host gate: a conf pinned to another box contributes nothing here. Note
  # this runs BEFORE the symlink/QUESTIONS work below too -- a job that
  # doesn't run on this host shouldn't claim this host's questions/ slot.
  if [ -n "${CRON_HOST:-}" ] && [ "$CRON_HOST" != "$SHORT_HOST" ]; then
    echo "skipping [$name]: CRON_HOST=$CRON_HOST, this is $SHORT_HOST" >&2
    continue
  fi

  conf_account="${CRON_ACCOUNT:-$LOCAL_ACCOUNT}"
  if [ "$conf_account" != "$LOCAL_ACCOUNT" ] && ! home_of "$conf_account" >/dev/null; then
    echo "ERROR [$name]: CRON_ACCOUNT=$conf_account is not a user on $SHORT_HOST -- skipping this conf" >&2
    ERRORS=$((ERRORS + 1))
    continue
  fi

  # One project, one dispatcher. A foreign-account job that is ALSO an
  # enabled participant in this account's paced rotation would run twice --
  # once from the runner here, once from that account's crontab. This is
  # the exact failure mode both aedile's and vkv-inventory's confs warn
  # about in prose; assert it instead.
  if [ "$conf_account" != "$LOCAL_ACCOUNT" ] && is_paced_enabled "$PROJECT"; then
    echo "ERROR [$name]: CRON_ACCOUNT=$conf_account, but '$PROJECT' is also an ENABLED participant in $LOCAL_ACCOUNT's ${PACED_CONF:-rotation} ($PACED_CONF_SRC) -- that is double dispatch. Park it there (enabled 0) or drop CRON_ACCOUNT, and re-run." >&2
    ERRORS=$((ERRORS + 1))
    continue
  fi

  # Symlink this project's .claude/QUESTIONS.md into questions/<PROJECT>.md
  # -- "does scheduler know about this" for the one thing a human actually
  # wants to browse across every project in one place, without duplicating
  # the file (a symlink, not a copy, so either path edits the same file).
  # PROJECT_REPO_PATH is optional -- a project with no local working copy
  # in this exact shape just doesn't get one.
  #
  # ANSWER_CHANNEL="issues" (2026-07-28) suppresses the symlink entirely.
  # Leaving one in place for a migrated project is worse than having none:
  # it is a file that LOOKS like the answer surface, sits in the same
  # directory as every other project's real one, and silently is not where
  # anyone reads or writes any more. The staleness this migration exists to
  # escape would come straight back wearing the old file's name.
  if [ -n "${PROJECT_REPO_PATH:-}" ] && [ "${ANSWER_CHANNEL:-file}" != "issues" ]; then
    # Self-contained-folder model: a migrated project sets
    # SCHEDULER_SUBDIR=".scheduler" -- a TOP-LEVEL dir, deliberately OUTSIDE
    # .claude/ -- so its FOCUS/QUESTIONS group under one folder it owns.
    # Not-yet-migrated projects default to ".claude", which is exactly the
    # legacy shape that hits the unattended "sensitive file" permission gate
    # on writes (confirmed 2026-07-20, see FOCUS.md "Permission gate" note)
    # -- SCHEDULER_SUBDIR=".scheduler" is the fix, not just a naming choice.
    sdir="${SCHEDULER_SUBDIR:-.claude}"
    QUESTIONS_LINKS+=("$PROJECT|$PROJECT_REPO_PATH/$sdir/QUESTIONS.md")
    # Same idea for FOCUS.md -- the per-project scope-input a nightly run
    # reads, browsable/editable from one place (../focus/) without copying.
    FOCUS_LINKS+=("$PROJECT|$PROJECT_REPO_PATH/$sdir/FOCUS.md")
  fi

  # --- Tier 1 (sweep): no auto-scheduling concept for this tier -- it's
  # meant to run every N minutes in a fixed window, not once nightly, so
  # "batching" doesn't apply the same way. ---
  jn="${SWEEP_JOB_NAME:-}"; sc="${SWEEP_SCRIPT:-}"; cr="${SWEEP_CRON:-}"
  if is_paced "$PROJECT" && { [ -n "$jn" ] || [ -n "$sc" ] || [ -n "$cr" ]; }; then
    echo "note [$name/SWEEP]: paced participant -- fixed cron suppressed, dispatched by ${RUNNER_JOB:-usage-paced-runner}" >&2
    jn=""; sc=""; cr=""   # fall through to the "not used" branch below
  fi
  if [ -z "$jn" ] && [ -z "$sc" ] && [ -z "$cr" ]; then
    : # not used for this project
  elif [ -z "$jn" ] || [ -z "$cr" ]; then
    echo "ERROR [$name/SWEEP]: SWEEP_JOB_NAME and SWEEP_CRON must both be set to enable Tier 1 (or leave the whole tier blank) -- skipping this tier" >&2
    ERRORS=$((ERRORS + 1))
  elif ! resolve_cmd SWEEP "$sc" "${SWEEP_PROMPT:-}" sweep; then
    echo "ERROR [$name/SWEEP]: $RESOLVE_ERR -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  elif ! validate_cron "$cr"; then
    echo "ERROR [$name/SWEEP]: SWEEP_CRON='$cr' isn't a valid 5-field cron expression -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  elif is_expired "$jn" "$conf_account"; then
    echo "skipping [$name/SWEEP]: job '$jn' expired ($(cat "$(home_of "$conf_account")/.local/share/$jn/expires_at" 2>/dev/null)) -- renew: rm $(home_of "$conf_account")/.local/share/$jn/expires_at (next run re-stamps now+EXPIRY_DAYS; bumping EXPIRY_DAYS alone does not renew)" >&2
  else
    cmd="$RESOLVE_OUT"
    add_managed_line "$conf_account" "$cr $cmd # scheduler:$PROJECT:SWEEP ($jn)"
  fi

  # --- Tier 2 (batch): BATCH_CRON="auto" (or left blank, with JOB_NAME
  # and SCRIPT both set) defers to the auto-stagger pass below, instead
  # of requiring a hand-picked, non-colliding literal time every time a
  # project registers. ---
  jn="${BATCH_JOB_NAME:-}"; sc="${BATCH_SCRIPT:-}"; cr="${BATCH_CRON:-}"
  if [ "$conf_account" = "$LOCAL_ACCOUNT" ] && is_paced "$PROJECT" && { [ -n "$jn" ] || [ -n "$sc" ] || [ -n "$cr" ]; }; then
    echo "note [$name/BATCH]: paced participant -- fixed cron suppressed, dispatched by ${RUNNER_JOB:-usage-paced-runner}" >&2
    jn=""; sc=""; cr=""   # fall through to the "not used" branch below
  fi
  if [ -z "$jn" ] && [ -z "$sc" ] && [ -z "$cr" ]; then
    : # not used for this project
  elif [ -z "$jn" ]; then
    echo "ERROR [$name/BATCH]: BATCH_JOB_NAME must be set to enable Tier 2 (or leave the whole tier blank) -- skipping this tier" >&2
    ERRORS=$((ERRORS + 1))
  elif ! resolve_cmd BATCH "$sc" "${BATCH_PROMPT:-}" batch; then
    echo "ERROR [$name/BATCH]: $RESOLVE_ERR -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  elif is_expired "$jn" "$conf_account"; then
    echo "skipping [$name/BATCH]: job '$jn' expired ($(cat "$(home_of "$conf_account")/.local/share/$jn/expires_at" 2>/dev/null)) -- renew: rm $(home_of "$conf_account")/.local/share/$jn/expires_at (next run re-stamps now+EXPIRY_DAYS; bumping EXPIRY_DAYS alone does not renew)" >&2
  elif [ -z "$cr" ] || [ "$cr" = "auto" ]; then
    AUTO_BATCH+=("$PROJECT|$jn|$RESOLVE_OUT|$conf_account")
  elif ! validate_cron "$cr"; then
    echo "ERROR [$name/BATCH]: BATCH_CRON='$cr' isn't a valid 5-field cron expression (or 'auto') -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  else
    cmd="$RESOLVE_OUT"
    BATCH_CRON_SEEN+=("$cr|$name")
    add_managed_line "$conf_account" "$cr $cmd # scheduler:$PROJECT:BATCH ($jn)"
  fi
done

# Assign auto-batch slots in a deterministic order (by project name), each
# BATCH_STAGGER_MINUTES apart from BATCH_BASE_TIME, skipping forward past
# any slot that would exactly collide with an EXPLICITLY set BATCH_CRON
# from another project (capped so a pathological config can't loop forever).
if [ "${#AUTO_BATCH[@]}" -gt 0 ]; then
  IFS=$'\n' AUTO_BATCH_SORTED=($(printf '%s\n' "${AUTO_BATCH[@]}" | sort)); unset IFS
  slot_idx=0
  for entry in "${AUTO_BATCH_SORTED[@]}"; do
    proj="${entry%%|*}"; rest="${entry#*|}"; jn="${rest%%|*}"; rest="${rest#*|}"
    sc="${rest%|*}"; acct="${rest##*|}"
    attempts=0
    while :; do
      read -r mm hh <<<"$(batch_slot_time "$slot_idx")"
      cr="$mm $hh * * *"
      collision=0
      for seen in "${BATCH_CRON_SEEN[@]}"; do
        [ "${seen%%|*}" = "$cr" ] && collision=1 && break
      done
      slot_idx=$((slot_idx + 1))
      attempts=$((attempts + 1))
      if [ "$collision" -eq 0 ] || [ "$attempts" -ge 48 ]; then
        break
      fi
    done
    BATCH_CRON_SEEN+=("$cr|$proj (auto)")
    add_managed_line "$acct" "$cr $sc # scheduler:$proj:BATCH ($jn, auto-batched)"
  done
fi

# Emit the single usage-paced dispatcher tick (if schedule/_runner.conf set it).
# This one line replaces the fixed nightly BATCH lines suppressed above.
if [ -n "$RUNNER_JOB" ] || [ -n "$RUNNER_CMD" ] || [ -n "$RUNNER_CRON" ]; then
  if [ "$RUNNER_OPTOUT" -eq 1 ]; then
    # Deliberate, and said out loud rather than silently omitted: a tick this
    # host does not run is a real difference from every other host, and the
    # only place it is visible is right here.
    echo "note [runner]: _runner.$SYNC_HOST.conf blanks RUNNER_CRON -- this host opts OUT of the runner tick _runner.conf arms" >&2
  elif [ -z "$RUNNER_JOB" ] || [ -z "$RUNNER_CMD" ] || [ -z "$RUNNER_CRON" ]; then
    echo "ERROR [runner]: _runner.conf needs RUNNER_JOB, RUNNER_CMD and RUNNER_CRON all set -- runner tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  elif ! validate_cron "$RUNNER_CRON"; then
    echo "ERROR [runner]: RUNNER_CRON='$RUNNER_CRON' isn't a valid 5-field cron expression -- runner tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  elif ! runner_why=$(meta_cmd_unrunnable "$RUNNER_CMD"); then
    echo "ERROR [runner]: RUNNER_CMD -- $runner_why -- runner tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  else
    # RUNNER_ENV is optional -- "VAR=val VAR2=val2" prepended verbatim
    # before the command (cron lines run through /bin/sh -c, so plain
    # leading assignments work same as on any shell command line). Lets
    # schedule/_runner.conf tune runner behavior (e.g. PACED_MAX_PER_TICK)
    # without touching RUNNER_CMD itself. See `scheduler pacing`.
    add_managed_line "$LOCAL_ACCOUNT" "$RUNNER_CRON ${RUNNER_ENV:+$RUNNER_ENV }$RUNNER_CMD # scheduler:$RUNNER_JOB:RUNNER (usage-paced dispatch)"
  fi
fi

# Emit the sweep tick (if schedule/_sweep.conf set it) -- independent of
# and not suppressed/affected by anything above.
if [ -n "$SWEEP_TICK_JOB" ] || [ -n "$SWEEP_TICK_CMD" ] || [ -n "$SWEEP_TICK_CRON" ]; then
  if [ "$SWEEP_OPTOUT" -eq 1 ]; then
    echo "note [sweep]: _sweep.$SYNC_HOST.conf blanks SWEEP_TICK_CRON -- this host opts OUT of the sweep tick _sweep.conf arms" >&2
  elif [ -z "$SWEEP_TICK_JOB" ] || [ -z "$SWEEP_TICK_CMD" ] || [ -z "$SWEEP_TICK_CRON" ]; then
    echo "ERROR [sweep]: _sweep.conf needs SWEEP_TICK_JOB, SWEEP_TICK_CMD and SWEEP_TICK_CRON all set -- sweep tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  elif ! validate_cron "$SWEEP_TICK_CRON"; then
    echo "ERROR [sweep]: SWEEP_TICK_CRON='$SWEEP_TICK_CRON' isn't a valid 5-field cron expression -- sweep tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  elif ! sweep_why=$(meta_cmd_unrunnable "$SWEEP_TICK_CMD"); then
    echo "ERROR [sweep]: SWEEP_TICK_CMD -- $sweep_why -- sweep tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  else
    add_managed_line "$LOCAL_ACCOUNT" "$SWEEP_TICK_CRON $SWEEP_TICK_CMD # scheduler:$SWEEP_TICK_JOB:SWEEP (reactive backstop)"
  fi
fi

# Warn (not fail) on two projects' Tier 2 sharing an identical cron
# expression -- both still run; the note is a nudge to stagger by hand
# (or switch to BATCH_CRON=auto). Auto-assigned slots are already
# collision-checked above, so this mainly catches two EXPLICIT times
# clashing.
if [ "${#BATCH_CRON_SEEN[@]}" -gt 1 ]; then
  for ((i = 0; i < ${#BATCH_CRON_SEEN[@]}; i++)); do
    for ((j = i + 1; j < ${#BATCH_CRON_SEEN[@]}; j++)); do
      cr_i="${BATCH_CRON_SEEN[$i]%%|*}"; name_i="${BATCH_CRON_SEEN[$i]#*|}"
      cr_j="${BATCH_CRON_SEEN[$j]%%|*}"; name_j="${BATCH_CRON_SEEN[$j]#*|}"
      if [ "$cr_i" = "$cr_j" ]; then
        echo "WARNING: $name_i and $name_j both run Tier 2 at '$cr_i' -- consider staggering (edit BATCH_CRON in either schedule/*.conf, or set BATCH_CRON=auto)" >&2
      fi
    done
  done
fi

if [ "$ERRORS" -gt 0 ]; then
  echo "-- $ERRORS error(s) above; the affected tier(s) were left OUT of the generated crontab, everything else proceeded --" >&2
fi

# Sync questions/<PROJECT>.md symlinks -- same preview-by-default,
# --apply-to-write rule as the crontab itself below. Each symlink points
# at a project's own .claude/QUESTIONS.md so it's browsable from one
# place (this directory) without duplicating the file.
QUESTIONS_HEADER='# Questions for the user

Running log, appended to (never overwritten or trimmed) by `/bug-sweep`
and `/nightly-batch` whenever something bigger than a routine tracker note
comes up. Clear an entry by deleting its line once you'"'"'ve actually read
and dealt with it; that'"'"'s the only thing that should ever remove
something from this file.
'

if [ "${#QUESTIONS_LINKS[@]}" -gt 0 ]; then
  if [ "$APPLY" -eq 0 ]; then
    echo "--- questions/ symlinks that would be created/updated (pass --apply to actually do this) ---"
    for entry in "${QUESTIONS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      echo "questions/$proj.md -> $target$([ -f "$target" ] || echo "  (target does not exist yet -- would be created with a header)")"
    done
  else
    mkdir -p "$QUESTIONS_DIR"
    for entry in "${QUESTIONS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      if [ ! -f "$target" ]; then
        mkdir -p "$(dirname "$target")"
        printf '%s' "$QUESTIONS_HEADER" > "$target"
        echo "created $target"
      fi
      ln -sfn "$target" "$QUESTIONS_DIR/$proj.md"
      echo "linked questions/$proj.md -> $target"
    done
  fi
fi

# Sync focus/<PROJECT>.md symlinks -- the per-project scope-input each
# nightly run reads (.claude/FOCUS.md), browsable/editable from one place.
# Unlike QUESTIONS.md this is NOT auto-created: FOCUS content is
# project-specific and fabricating an empty one would mislead a nightly run
# into thinking it has scope. A project without a real FOCUS.md is just
# noted and skipped here.
if [ "${#FOCUS_LINKS[@]}" -gt 0 ]; then
  if [ "$APPLY" -eq 0 ]; then
    echo "--- focus/ symlinks that would be created/updated (pass --apply to actually do this) ---"
    for entry in "${FOCUS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      if [ -f "$target" ]; then
        echo "focus/$proj.md -> $target"
      else
        echo "focus/$proj.md -> $target  (target does not exist yet -- skipped; add a .claude/FOCUS.md to link it)"
      fi
    done
  else
    mkdir -p "$FOCUS_DIR"
    for entry in "${FOCUS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      if [ -f "$target" ]; then
        ln -sfn "$target" "$FOCUS_DIR/$proj.md"
        echo "linked focus/$proj.md -> $target"
      else
        echo "skipped focus/$proj.md -- no FOCUS.md at $target yet"
      fi
    done
  fi
fi

WRITE_ERRORS=0

for acct in "${ACCT_ORDER[@]}"; do
  acct_backup_dir="$BACKUP_DIR"
  acct_label="$acct"
  if [ "$acct" != "$LOCAL_ACCOUNT" ]; then
    acct_backup_dir="$BACKUP_DIR/$acct"
    acct_label="$acct (foreign account, via sudo -u)"
  fi

  # READ BEFORE WRITE. A failed read is fatal for this account: the
  # unmanaged lines we'd be preserving are exactly what we cannot see.
  if ! CURRENT_CRONTAB="$(read_crontab_for "$acct")"; then
    echo "ERROR [$acct]: cannot read that account's crontab -- refusing to write its managed block." >&2
    echo "       Needs passwordless 'sudo -u $acct crontab -l'. Without the read, writing would" >&2
    echo "       silently discard any unmanaged lines and could double-dispatch an existing job." >&2
    WRITE_ERRORS=$((WRITE_ERRORS + 1))
    continue
  fi

  KEPT="$(awk -v b="$MARK_BEGIN" -v e="$MARK_END" '
    $0==b {skip=1; next}
    $0==e {skip=0; next}
    skip {next}
    {print}
  ' <<<"$CURRENT_CRONTAB")"

  # Unmanaged lines that reference a job name we are about to manage mean
  # the same job is installed twice under different ownership -- the exact
  # failure the aedile/vkv-inventory migration produced. Loud, not fatal:
  # the human has to pick which one survives.
  while IFS= read -r mline; do
    [ -n "$mline" ] || continue
    # The command this managed line runs, i.e. the line minus its leading
    # 5-field cron expression and minus the trailing "# scheduler:..." tag.
    mcmd="$(awk '{ $1=$2=$3=$4=$5=""; sub(/^ +/,""); sub(/ *# scheduler:.*$/,""); print }' <<<"$mline")"
    [ -n "$mcmd" ] || continue
    while IFS= read -r kline; do
      [ -n "$kline" ] || continue
      case "$kline" in \#*) continue ;; esac
      kcmd="$(awk '{ $1=$2=$3=$4=$5=""; sub(/^ +/,""); print }' <<<"$kline")"
      [ "$kcmd" = "$mcmd" ] || continue
      if [ "$ADOPT" -eq 1 ]; then
        echo "adopting [$acct]: '$mcmd' was hand-installed; the managed block takes it over (raw line dropped)"
        KEPT="$(grep -vxF -- "$kline" <<<"$KEPT")"
      else
        echo "WARNING [$acct]: an UNMANAGED line already runs '$mcmd' -- installing the managed block as well would run it TWICE. Re-run with --adopt to take the existing line over, or remove it by hand." >&2
      fi
    done <<<"$KEPT"
  done <<<"${ACCT_LINES[$acct]}"

  NEW_FILE="/tmp/sync-crontab.$$.$acct.new"
  {
    printf '%s\n' "$KEPT"
    echo "$MARK_BEGIN"
    printf '%s' "${ACCT_LINES[$acct]}"
    echo "$MARK_END"
  } > "$NEW_FILE"

  if [ "$APPLY" -eq 0 ]; then
    echo "--- preview only for $acct_label (pass --apply to actually install) ---"
    cat "$NEW_FILE"
    rm -f "$NEW_FILE"
    continue
  fi

  mkdir -p "$acct_backup_dir"
  BACKUP_FILE="$acct_backup_dir/$(date -Is).bak"
  printf '%s\n' "$CURRENT_CRONTAB" > "$BACKUP_FILE"
  echo "backed up $acct's crontab to $BACKUP_FILE"

  if [ "$acct" = "$LOCAL_ACCOUNT" ]; then
    crontab "$NEW_FILE"
  else
    # stdin, not a path: the file is owned by the invoker and unreadable
    # to the target account under a sane umask.
    sudo -n -u "$acct" crontab - < "$NEW_FILE"
  fi
  rc=$?
  rm -f "$NEW_FILE"
  if [ "$rc" -ne 0 ]; then
    echo "ERROR [$acct]: crontab install failed (rc=$rc) -- restore with: ${acct/#$LOCAL_ACCOUNT/}${acct:+sudo -n -u $acct }crontab $BACKUP_FILE" >&2
    WRITE_ERRORS=$((WRITE_ERRORS + 1))
    continue
  fi
  echo "crontab updated for $acct_label. current state:"
  read_crontab_for "$acct"
done

if [ "$WRITE_ERRORS" -gt 0 ]; then
  echo "-- $WRITE_ERRORS account(s) above were NOT written --" >&2
  exit 1
fi
[ "$ERRORS" -gt 0 ] && exit 1
exit 0
