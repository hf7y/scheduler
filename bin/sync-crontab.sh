#!/usr/bin/env bash
# Reads every ../schedule/*.conf entry and rewrites the REAL crontab's
# scheduler-managed block to match. This is the one and only place that
# writes cron lines for scheduler-managed jobs -- lib/sweep-loop-common.sh
# itself no longer edits crontab (see its expiry block).
#
# "Registering" a project = drop a schedule/<project>.conf (see
# ../examples/schedule-entry.conf.template) and run this script.
# "Moving hours around" = edit that file's SWEEP_CRON/BATCH_CRON and
# run this script again. "Deregistering" = delete the file and run again.
#
# Safe by default: prints what it WOULD install and exits. Nothing is
# written to the real crontab unless you pass --apply.
#
# Only ever touches lines between the BEGIN/END markers below -- anything
# else already in your crontab (including any not-yet-migrated raw entry
# like chezz's original unrestricted line) is left exactly as-is. If
# you're migrating an existing raw entry onto a schedule/*.conf file,
# remove the old raw line yourself first (crontab -e) or you'll end up
# with two entries for the same job.
#
# TWO SCOPING AXES (2026-07-25). Both default to "here, as me", so every
# existing conf behaves exactly as before:
#
#   CRON_ACCOUNT="svc-vaporwave"   install this project's lines into THAT
#                                  user's crontab instead of the invoking
#                                  user's. Same managed-block discipline,
#                                  one block per account, one backup dir
#                                  per account. Requires passwordless
#                                  `sudo -u <account> crontab` (zach has
#                                  `(svc-vaporwave) NOPASSWD: ALL`).
#   CRON_HOST="mandark"            only install on that short hostname;
#                                  other hosts skip the conf entirely.
#
# CRON_HOST is what makes moving a service account to another box a
# one-field edit rather than a migration: the conf is the single source of
# truth for WHERE and AS WHOM a job runs, mirroring how
# usage-paced-runner.sh already resolves schedule/_paced.<host>.conf. To
# move svc-vaporwave's jobs to dexter, set CRON_HOST="dexter", run this on
# dexter with --apply, then re-run on mandark with --apply to retract the
# now-foreign block (an unlisted host produces an EMPTY managed block,
# which removes the lines rather than orphaning them).
#
# A foreign account's crontab is READ before it is written, exactly like
# the local one. If that read fails, the block for that account is NOT
# written and the script exits nonzero -- writing a managed block without
# first seeing the unmanaged lines would silently discard them, and would
# hide an already-installed job of the same name (double dispatch).

set -uo pipefail

SCHED_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCHEDULE_DIR="$SCHED_DIR/schedule"
BACKUP_DIR="$SCHED_DIR/.crontab-backups"
SCHEDULER_RUN="$SCHED_DIR/bin/scheduler-run"

MARK_BEGIN="# >>> scheduler-managed (generated by bin/sync-crontab.sh -- edit schedule/*.conf instead, then re-run) >>>"
MARK_END="# <<< scheduler-managed <<<"

LOCAL_ACCOUNT="$(id -un)"
SHORT_HOST="$(hostname -s)"

# Lines are bucketed per account: ACCT_LINES[acct] holds a newline-joined
# block, ACCT_ORDER preserves first-seen order so previews are stable.
declare -A ACCT_LINES=()
ACCT_ORDER=("$LOCAL_ACCOUNT")
ACCT_LINES["$LOCAL_ACCOUNT"]=""

add_managed_line() {
  # $1 = account, $2 = crontab line
  local acct="$1" line="$2"
  if [ -z "${ACCT_LINES[$acct]+set}" ]; then
    ACCT_LINES["$acct"]=""
    ACCT_ORDER+=("$acct")
  fi
  ACCT_LINES["$acct"]+="$line"$'\n'
}

home_of() {
  # Expiry state lives under the OWNING account's home, not the invoker's.
  local acct="$1" h
  if [ "$acct" = "$LOCAL_ACCOUNT" ]; then printf '%s' "$HOME"; return 0; fi
  h="$(getent passwd "$acct" | cut -d: -f6)"
  [ -n "$h" ] || return 1
  printf '%s' "$h"
}

# Read one account's current crontab. Echoes it on stdout; returns nonzero
# only when the read could not be performed at all (missing sudo rights,
# unknown user) -- an empty crontab is a successful read of nothing, which
# `crontab -l` reports as exit 1, hence the explicit no-crontab match.
read_crontab_for() {
  local acct="$1" out rc
  if [ "$acct" = "$LOCAL_ACCOUNT" ]; then
    crontab -l 2>/dev/null || true
    return 0
  fi
  out="$(sudo -n -u "$acct" crontab -l 2>&1)"; rc=$?
  if [ "$rc" -ne 0 ]; then
    case "$out" in
      *"no crontab for"*) printf '' ; return 0 ;;
      *) printf '%s' "$out" >&2 ; return 1 ;;
    esac
  fi
  printf '%s' "$out"
}

APPLY=0
for arg in "$@"; do
  case "$arg" in
    --apply) APPLY=1 ;;
    -h|--help)
      echo "Usage: $0 [--apply]"
      echo "  (no args)  preview the crontab this would produce"
      echo "  --apply    back up the current crontab, then actually write it"
      exit 0
      ;;
    *) echo "unknown arg: $arg (see --help)" >&2; exit 1 ;;
  esac
done

if [ ! -d "$SCHEDULE_DIR" ]; then
  echo "no $SCHEDULE_DIR yet -- nothing to sync" >&2
  exit 0
fi

# Batch config for Tier 2 auto-staggering -- see "BATCH_CRON=auto" below.
# schedule/_batch.conf is optional (leading underscore keeps it out of the
# *.conf glob every project's entry is read from, below).
BATCH_BASE_TIME="01:00"
BATCH_STAGGER_MINUTES=30
if [ -f "$SCHEDULE_DIR/_batch.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_batch.conf"
fi
BATCH_BASE_MINUTES=$(( 10#${BATCH_BASE_TIME%%:*} * 60 + 10#${BATCH_BASE_TIME##*:} ))

# $1 = slot index (0-based) -> prints "MIN HOUR" for that slot, wrapping
# past midnight if the batch runs long enough to need it.
batch_slot_time() {
  local idx="$1"
  local total=$(( (BATCH_BASE_MINUTES + idx * BATCH_STAGGER_MINUTES) % 1440 ))
  printf '%d %d' "$((total % 60))" "$((total / 60))"
}

# --- Paced-runner meta (optional) ---------------------------------------------
# schedule/_runner.conf turns on usage-paced dispatch: one frequent tick runs
# bin/usage-paced-runner.sh, which round-robins the ENABLED participants in
# schedule/_paced.conf whenever usage-gate.sh reports spare weekly quota. With
# PACED_SUPPRESS_BATCH=1, any project that IS a paced participant gets its fixed
# nightly BATCH cron line suppressed below (the runner dispatches it instead) --
# each project's BATCH_* config stays intact, so deleting _runner.conf restores
# the old fixed-time behaviour on the next sync. SWEEP (bug-sweep) tiers are
# never suppressed.
RUNNER_JOB=""; RUNNER_CMD=""; RUNNER_CRON=""; RUNNER_ENV=""; PACED_SUPPRESS_BATCH=0
if [ -f "$SCHEDULE_DIR/_runner.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_runner.conf"
fi

# --- Sweep tick meta (optional) ------------------------------------------------
# schedule/_sweep.conf's mere presence adds ONE fixed, always-on tick for
# `scheduler sweep` -- deliberately separate from the usage-paced dispatch
# above (sweep is pure git/bash, zero API cost, so gating it behind
# usage-gate.sh would protect a budget it never touches).
SWEEP_TICK_JOB=""; SWEEP_TICK_CMD=""; SWEEP_TICK_CRON=""
if [ -f "$SCHEDULE_DIR/_sweep.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_sweep.conf"
fi
PACED_SET=" "          # listed in _paced.conf at all -> runner owns Tier 2
PACED_ENABLED_SET=" "  # listed AND enabled -> actually dispatches here
if [ "${PACED_SUPPRESS_BATCH:-0}" = "1" ] && [ -f "$SCHEDULE_DIR/_paced.conf" ]; then
  while IFS='|' read -r pname penabled _; do
    case "$pname" in ''|\#*) continue ;; esac
    # MEMBERSHIP, not the enabled flag (fixed 2026-07-25). Being listed in
    # _paced.conf means the usage-paced runner owns this project's Tier 2,
    # full stop. The flag says whether it currently dispatches -- parked
    # (0) means "don't run it", NOT "fall back to a fixed nightly cron
    # line". Reading the flag here meant parking a project silently
    # re-armed its fixed BATCH line on the next --apply: caught in preview
    # today, where crt (moved to dexter) plus the four projects parked on
    # 2026-07-24 all wanted nightly slots that the live crontab correctly
    # does not have. Parking is an admission-control decision; a sync
    # script must not overturn it as a side effect.
    PACED_SET+="${pname// /} "
    # Separately: is it actually DISPATCHING here? Only an enabled entry can
    # collide with a foreign account's crontab (see the double-dispatch guard).
    [ "${penabled// /}" = "1" ] && PACED_ENABLED_SET+="${pname// /} "
  done < "$SCHEDULE_DIR/_paced.conf"
fi
is_paced() { case "$PACED_SET" in *" $1 "*) return 0 ;; *) return 1 ;; esac; }
is_paced_enabled() { case "$PACED_ENABLED_SET" in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

shopt -s nullglob
CONF_FILES=()
for f in "$SCHEDULE_DIR"/*.conf; do
  case "$(basename "$f")" in
    _*) continue ;;   # meta config (e.g. _batch.conf), not a project
  esac
  CONF_FILES+=("$f")
done
shopt -u nullglob

if [ "${#CONF_FILES[@]}" -eq 0 ]; then
  echo "no schedule/*.conf entries yet -- nothing to sync" >&2
  exit 0
fi

BATCH_CRON_SEEN=()   # "cron_expr|project" pairs, for collision detection
AUTO_BATCH=()         # "project|job_name|script" pairs awaiting an auto slot
ERRORS=0

is_expired() {
  # $1 = JOB_NAME. Mirrors the expiry check lib/sweep-loop-common.sh
  # itself does -- same file, same ISO-8601 string comparison.
  local job_name="$1" acct="${2:-$LOCAL_ACCOUNT}" acct_home
  acct_home="$(home_of "$acct")" || return 1
  local expires_at_file="$acct_home/.local/share/$job_name/expires_at"
  [ -f "$expires_at_file" ] || return 1
  local expires_at now_is
  expires_at=$(cat "$expires_at_file")
  now_is=$(date -Is)
  [[ "$now_is" > "$expires_at" ]]
}

validate_cron() {
  # $1 = cron expression. Exactly 5 whitespace-separated fields.
  local field_count
  field_count=$(awk '{print NF}' <<<"$1")
  [ "$field_count" -eq 5 ]
}

# Resolve the command cron should run for one tier, honoring backwards
# compatibility. $1=tier label (SWEEP|BATCH), $2=<TIER>_SCRIPT value,
# $3=<TIER>_PROMPT value, $4=scheduler-run subcommand (sweep|batch). Echoes
# the command string on success; sets RESOLVE_ERR and returns 1 otherwise.
# Precedence: a legacy *_SCRIPT wins (proven, unchanged) -- drop it to switch
# a tier onto scheduler-run, which reads REPO_URL/<TIER>_PROMPT from the conf.
RESOLVE_ERR=""
resolve_cmd() {
  local tier="$1" script="$2" prompt="$3" sub="$4"
  RESOLVE_ERR=""
  if [ -n "$script" ]; then
    if [ ! -x "$script" ]; then
      RESOLVE_ERR="${tier}_SCRIPT=$script does not exist or isn't executable"
      return 1
    fi
    printf '%s' "$script"; return 0
  fi
  # New mode: no legacy wrapper -> run via scheduler-run from the conf.
  if [ ! -x "$SCHEDULER_RUN" ]; then
    RESOLVE_ERR="scheduler-run not found/executable at $SCHEDULER_RUN"
    return 1
  fi
  if [ -z "${REPO_URL:-}" ]; then
    RESOLVE_ERR="no ${tier}_SCRIPT and no REPO_URL set -- provide one (see examples/schedule-entry.conf.template)"
    return 1
  fi
  if [ -z "$prompt" ]; then
    RESOLVE_ERR="no ${tier}_SCRIPT and no ${tier}_PROMPT set -- provide one"
    return 1
  fi
  printf '%s %s %s' "$SCHEDULER_RUN" "$PROJECT" "$sub"; return 0
}

QUESTIONS_DIR="$SCHED_DIR/questions"
QUESTIONS_LINKS=()   # "project|target_path" pairs, built alongside the crontab lines below
FOCUS_DIR="$SCHED_DIR/focus"
FOCUS_LINKS=()       # "project|target_path" pairs -- mirrors QUESTIONS_LINKS

for conf in "${CONF_FILES[@]}"; do
  # Reset every field this format understands so a conf file missing a
  # var can't silently inherit the previous file's value.
  unset PROJECT SWEEP_JOB_NAME SWEEP_SCRIPT SWEEP_CRON
  unset BATCH_JOB_NAME BATCH_SCRIPT BATCH_CRON PROJECT_REPO_PATH
  # Runtime fields (read by scheduler-run) that also gate command resolution
  # here -- reset so one conf's value can't leak into the next.
  unset REPO_URL SWEEP_PROMPT BATCH_PROMPT SCHEDULER_SUBDIR
  # Scoping axes -- reset so one conf's account/host can't leak into the next.
  unset CRON_ACCOUNT CRON_HOST
  # shellcheck disable=SC1090
  source "$conf"

  name=$(basename "$conf" .conf)
  PROJECT="${PROJECT:-$name}"

  # Host gate: a conf pinned to another box contributes nothing here. Note
  # this runs BEFORE the symlink/QUESTIONS work below too -- a job that
  # doesn't run on this host shouldn't claim this host's questions/ slot.
  if [ -n "${CRON_HOST:-}" ] && [ "$CRON_HOST" != "$SHORT_HOST" ]; then
    echo "skipping [$name]: CRON_HOST=$CRON_HOST, this is $SHORT_HOST" >&2
    continue
  fi

  conf_account="${CRON_ACCOUNT:-$LOCAL_ACCOUNT}"
  if [ "$conf_account" != "$LOCAL_ACCOUNT" ] && ! home_of "$conf_account" >/dev/null; then
    echo "ERROR [$name]: CRON_ACCOUNT=$conf_account is not a user on $SHORT_HOST -- skipping this conf" >&2
    ERRORS=$((ERRORS + 1))
    continue
  fi

  # One project, one dispatcher. A foreign-account job that is ALSO an
  # enabled participant in this account's paced rotation would run twice --
  # once from the runner here, once from that account's crontab. This is
  # the exact failure mode both aedile's and vkv-inventory's confs warn
  # about in prose; assert it instead.
  if [ "$conf_account" != "$LOCAL_ACCOUNT" ] && is_paced_enabled "$PROJECT"; then
    echo "ERROR [$name]: CRON_ACCOUNT=$conf_account, but '$PROJECT' is also an ENABLED participant in $LOCAL_ACCOUNT's schedule/_paced.conf -- that is double dispatch. Set its _paced.conf weight to 0 (or drop CRON_ACCOUNT) and re-run." >&2
    ERRORS=$((ERRORS + 1))
    continue
  fi

  # Symlink this project's .claude/QUESTIONS.md into questions/<PROJECT>.md
  # -- "does scheduler know about this" for the one thing a human actually
  # wants to browse across every project in one place, without duplicating
  # the file (a symlink, not a copy, so either path edits the same file).
  # PROJECT_REPO_PATH is optional -- a project with no local working copy
  # in this exact shape just doesn't get one.
  if [ -n "${PROJECT_REPO_PATH:-}" ]; then
    # Self-contained-folder model: a migrated project sets
    # SCHEDULER_SUBDIR=".scheduler" -- a TOP-LEVEL dir, deliberately OUTSIDE
    # .claude/ -- so its FOCUS/QUESTIONS group under one folder it owns.
    # Not-yet-migrated projects default to ".claude", which is exactly the
    # legacy shape that hits the unattended "sensitive file" permission gate
    # on writes (confirmed 2026-07-20, see FOCUS.md "Permission gate" note)
    # -- SCHEDULER_SUBDIR=".scheduler" is the fix, not just a naming choice.
    sdir="${SCHEDULER_SUBDIR:-.claude}"
    QUESTIONS_LINKS+=("$PROJECT|$PROJECT_REPO_PATH/$sdir/QUESTIONS.md")
    # Same idea for FOCUS.md -- the per-project scope-input a nightly run
    # reads, browsable/editable from one place (../focus/) without copying.
    FOCUS_LINKS+=("$PROJECT|$PROJECT_REPO_PATH/$sdir/FOCUS.md")
  fi

  # --- Tier 1 (sweep): no auto-scheduling concept for this tier -- it's
  # meant to run every N minutes in a fixed window, not once nightly, so
  # "batching" doesn't apply the same way. ---
  jn="${SWEEP_JOB_NAME:-}"; sc="${SWEEP_SCRIPT:-}"; cr="${SWEEP_CRON:-}"
  if [ -z "$jn" ] && [ -z "$sc" ] && [ -z "$cr" ]; then
    : # not used for this project
  elif [ -z "$jn" ] || [ -z "$cr" ]; then
    echo "ERROR [$name/SWEEP]: SWEEP_JOB_NAME and SWEEP_CRON must both be set to enable Tier 1 (or leave the whole tier blank) -- skipping this tier" >&2
    ERRORS=$((ERRORS + 1))
  elif ! cmd=$(resolve_cmd SWEEP "$sc" "${SWEEP_PROMPT:-}" sweep); then
    echo "ERROR [$name/SWEEP]: $RESOLVE_ERR -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  elif ! validate_cron "$cr"; then
    echo "ERROR [$name/SWEEP]: SWEEP_CRON='$cr' isn't a valid 5-field cron expression -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  elif is_expired "$jn" "$conf_account"; then
    echo "skipping [$name/SWEEP]: job '$jn' expired ($(cat "$(home_of "$conf_account")/.local/share/$jn/expires_at" 2>/dev/null)) -- bump EXPIRY_DAYS and re-run this script to renew" >&2
  else
    add_managed_line "$conf_account" "$cr $cmd # scheduler:$PROJECT:SWEEP ($jn)"
  fi

  # --- Tier 2 (batch): BATCH_CRON="auto" (or left blank, with JOB_NAME
  # and SCRIPT both set) defers to the auto-stagger pass below, instead
  # of requiring a hand-picked, non-colliding literal time every time a
  # project registers. ---
  jn="${BATCH_JOB_NAME:-}"; sc="${BATCH_SCRIPT:-}"; cr="${BATCH_CRON:-}"
  if [ "$conf_account" = "$LOCAL_ACCOUNT" ] && is_paced "$PROJECT" && { [ -n "$jn" ] || [ -n "$sc" ] || [ -n "$cr" ]; }; then
    echo "note [$name/BATCH]: paced participant -- fixed cron suppressed, dispatched by ${RUNNER_JOB:-usage-paced-runner}" >&2
    jn=""; sc=""; cr=""   # fall through to the "not used" branch below
  fi
  if [ -z "$jn" ] && [ -z "$sc" ] && [ -z "$cr" ]; then
    : # not used for this project
  elif [ -z "$jn" ]; then
    echo "ERROR [$name/BATCH]: BATCH_JOB_NAME must be set to enable Tier 2 (or leave the whole tier blank) -- skipping this tier" >&2
    ERRORS=$((ERRORS + 1))
  elif ! cmd=$(resolve_cmd BATCH "$sc" "${BATCH_PROMPT:-}" batch); then
    echo "ERROR [$name/BATCH]: $RESOLVE_ERR -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  elif is_expired "$jn" "$conf_account"; then
    echo "skipping [$name/BATCH]: job '$jn' expired ($(cat "$(home_of "$conf_account")/.local/share/$jn/expires_at" 2>/dev/null)) -- bump EXPIRY_DAYS and re-run this script to renew" >&2
  elif [ -z "$cr" ] || [ "$cr" = "auto" ]; then
    AUTO_BATCH+=("$PROJECT|$jn|$cmd|$conf_account")
  elif ! validate_cron "$cr"; then
    echo "ERROR [$name/BATCH]: BATCH_CRON='$cr' isn't a valid 5-field cron expression (or 'auto') -- skipping" >&2
    ERRORS=$((ERRORS + 1))
  else
    BATCH_CRON_SEEN+=("$cr|$name")
    add_managed_line "$conf_account" "$cr $cmd # scheduler:$PROJECT:BATCH ($jn)"
  fi
done

# Assign auto-batch slots in a deterministic order (by project name), each
# BATCH_STAGGER_MINUTES apart from BATCH_BASE_TIME, skipping forward past
# any slot that would exactly collide with an EXPLICITLY set BATCH_CRON
# from another project (capped so a pathological config can't loop forever).
if [ "${#AUTO_BATCH[@]}" -gt 0 ]; then
  IFS=$'\n' AUTO_BATCH_SORTED=($(printf '%s\n' "${AUTO_BATCH[@]}" | sort)); unset IFS
  slot_idx=0
  for entry in "${AUTO_BATCH_SORTED[@]}"; do
    proj="${entry%%|*}"; rest="${entry#*|}"; jn="${rest%%|*}"; rest="${rest#*|}"
    sc="${rest%|*}"; acct="${rest##*|}"
    attempts=0
    while :; do
      read -r mm hh <<<"$(batch_slot_time "$slot_idx")"
      cr="$mm $hh * * *"
      collision=0
      for seen in "${BATCH_CRON_SEEN[@]}"; do
        [ "${seen%%|*}" = "$cr" ] && collision=1 && break
      done
      slot_idx=$((slot_idx + 1))
      attempts=$((attempts + 1))
      if [ "$collision" -eq 0 ] || [ "$attempts" -ge 48 ]; then
        break
      fi
    done
    BATCH_CRON_SEEN+=("$cr|$proj (auto)")
    add_managed_line "$acct" "$cr $sc # scheduler:$proj:BATCH ($jn, auto-batched)"
  done
fi

# Emit the single usage-paced dispatcher tick (if schedule/_runner.conf set it).
# This one line replaces the fixed nightly BATCH lines suppressed above.
if [ -n "$RUNNER_JOB" ] || [ -n "$RUNNER_CMD" ] || [ -n "$RUNNER_CRON" ]; then
  if [ -z "$RUNNER_JOB" ] || [ -z "$RUNNER_CMD" ] || [ -z "$RUNNER_CRON" ]; then
    echo "ERROR [runner]: _runner.conf needs RUNNER_JOB, RUNNER_CMD and RUNNER_CRON all set -- runner tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  elif ! validate_cron "$RUNNER_CRON"; then
    echo "ERROR [runner]: RUNNER_CRON='$RUNNER_CRON' isn't a valid 5-field cron expression -- runner tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  else
    # RUNNER_ENV is optional -- "VAR=val VAR2=val2" prepended verbatim
    # before the command (cron lines run through /bin/sh -c, so plain
    # leading assignments work same as on any shell command line). Lets
    # schedule/_runner.conf tune runner behavior (e.g. PACED_MAX_PER_TICK)
    # without touching RUNNER_CMD itself. See `scheduler pacing`.
    add_managed_line "$LOCAL_ACCOUNT" "$RUNNER_CRON ${RUNNER_ENV:+$RUNNER_ENV }$RUNNER_CMD # scheduler:$RUNNER_JOB:RUNNER (usage-paced dispatch)"
  fi
fi

# Emit the sweep tick (if schedule/_sweep.conf set it) -- independent of
# and not suppressed/affected by anything above.
if [ -n "$SWEEP_TICK_JOB" ] || [ -n "$SWEEP_TICK_CMD" ] || [ -n "$SWEEP_TICK_CRON" ]; then
  if [ -z "$SWEEP_TICK_JOB" ] || [ -z "$SWEEP_TICK_CMD" ] || [ -z "$SWEEP_TICK_CRON" ]; then
    echo "ERROR [sweep]: _sweep.conf needs SWEEP_TICK_JOB, SWEEP_TICK_CMD and SWEEP_TICK_CRON all set -- sweep tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  elif ! validate_cron "$SWEEP_TICK_CRON"; then
    echo "ERROR [sweep]: SWEEP_TICK_CRON='$SWEEP_TICK_CRON' isn't a valid 5-field cron expression -- sweep tick omitted" >&2
    ERRORS=$((ERRORS + 1))
  else
    add_managed_line "$LOCAL_ACCOUNT" "$SWEEP_TICK_CRON $SWEEP_TICK_CMD # scheduler:$SWEEP_TICK_JOB:SWEEP (reactive backstop)"
  fi
fi

# Warn (not fail) on two projects' Tier 2 sharing an identical cron
# expression -- both still run; the note is a nudge to stagger by hand
# (or switch to BATCH_CRON=auto). Auto-assigned slots are already
# collision-checked above, so this mainly catches two EXPLICIT times
# clashing.
if [ "${#BATCH_CRON_SEEN[@]}" -gt 1 ]; then
  for ((i = 0; i < ${#BATCH_CRON_SEEN[@]}; i++)); do
    for ((j = i + 1; j < ${#BATCH_CRON_SEEN[@]}; j++)); do
      cr_i="${BATCH_CRON_SEEN[$i]%%|*}"; name_i="${BATCH_CRON_SEEN[$i]#*|}"
      cr_j="${BATCH_CRON_SEEN[$j]%%|*}"; name_j="${BATCH_CRON_SEEN[$j]#*|}"
      if [ "$cr_i" = "$cr_j" ]; then
        echo "WARNING: $name_i and $name_j both run Tier 2 at '$cr_i' -- consider staggering (edit BATCH_CRON in either schedule/*.conf, or set BATCH_CRON=auto)" >&2
      fi
    done
  done
fi

if [ "$ERRORS" -gt 0 ]; then
  echo "-- $ERRORS error(s) above; the affected tier(s) were left OUT of the generated crontab, everything else proceeded --" >&2
fi

# Sync questions/<PROJECT>.md symlinks -- same preview-by-default,
# --apply-to-write rule as the crontab itself below. Each symlink points
# at a project's own .claude/QUESTIONS.md so it's browsable from one
# place (this directory) without duplicating the file.
QUESTIONS_HEADER='# Questions for the user

Running log, appended to (never overwritten or trimmed) by `/bug-sweep`
and `/nightly-batch` whenever something bigger than a routine tracker note
comes up. Clear an entry by deleting its line once you'"'"'ve actually read
and dealt with it; that'"'"'s the only thing that should ever remove
something from this file.
'

if [ "${#QUESTIONS_LINKS[@]}" -gt 0 ]; then
  if [ "$APPLY" -eq 0 ]; then
    echo "--- questions/ symlinks that would be created/updated (pass --apply to actually do this) ---"
    for entry in "${QUESTIONS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      echo "questions/$proj.md -> $target$([ -f "$target" ] || echo "  (target does not exist yet -- would be created with a header)")"
    done
  else
    mkdir -p "$QUESTIONS_DIR"
    for entry in "${QUESTIONS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      if [ ! -f "$target" ]; then
        mkdir -p "$(dirname "$target")"
        printf '%s' "$QUESTIONS_HEADER" > "$target"
        echo "created $target"
      fi
      ln -sfn "$target" "$QUESTIONS_DIR/$proj.md"
      echo "linked questions/$proj.md -> $target"
    done
  fi
fi

# Sync focus/<PROJECT>.md symlinks -- the per-project scope-input each
# nightly run reads (.claude/FOCUS.md), browsable/editable from one place.
# Unlike QUESTIONS.md this is NOT auto-created: FOCUS content is
# project-specific and fabricating an empty one would mislead a nightly run
# into thinking it has scope. A project without a real FOCUS.md is just
# noted and skipped here.
if [ "${#FOCUS_LINKS[@]}" -gt 0 ]; then
  if [ "$APPLY" -eq 0 ]; then
    echo "--- focus/ symlinks that would be created/updated (pass --apply to actually do this) ---"
    for entry in "${FOCUS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      if [ -f "$target" ]; then
        echo "focus/$proj.md -> $target"
      else
        echo "focus/$proj.md -> $target  (target does not exist yet -- skipped; add a .claude/FOCUS.md to link it)"
      fi
    done
  else
    mkdir -p "$FOCUS_DIR"
    for entry in "${FOCUS_LINKS[@]}"; do
      proj="${entry%%|*}"; target="${entry#*|}"
      if [ -f "$target" ]; then
        ln -sfn "$target" "$FOCUS_DIR/$proj.md"
        echo "linked focus/$proj.md -> $target"
      else
        echo "skipped focus/$proj.md -- no FOCUS.md at $target yet"
      fi
    done
  fi
fi

WRITE_ERRORS=0

for acct in "${ACCT_ORDER[@]}"; do
  acct_backup_dir="$BACKUP_DIR"
  acct_label="$acct"
  if [ "$acct" != "$LOCAL_ACCOUNT" ]; then
    acct_backup_dir="$BACKUP_DIR/$acct"
    acct_label="$acct (foreign account, via sudo -u)"
  fi

  # READ BEFORE WRITE. A failed read is fatal for this account: the
  # unmanaged lines we'd be preserving are exactly what we cannot see.
  if ! CURRENT_CRONTAB="$(read_crontab_for "$acct")"; then
    echo "ERROR [$acct]: cannot read that account's crontab -- refusing to write its managed block." >&2
    echo "       Needs passwordless 'sudo -u $acct crontab -l'. Without the read, writing would" >&2
    echo "       silently discard any unmanaged lines and could double-dispatch an existing job." >&2
    WRITE_ERRORS=$((WRITE_ERRORS + 1))
    continue
  fi

  KEPT="$(awk -v b="$MARK_BEGIN" -v e="$MARK_END" '
    $0==b {skip=1; next}
    $0==e {skip=0; next}
    skip {next}
    {print}
  ' <<<"$CURRENT_CRONTAB")"

  # Unmanaged lines that reference a job name we are about to manage mean
  # the same job is installed twice under different ownership -- the exact
  # failure the aedile/vkv-inventory migration produced. Loud, not fatal:
  # the human has to pick which one survives.
  while IFS= read -r mline; do
    [ -n "$mline" ] || continue
    mjob="${mline##*# scheduler:}"; mjob="${mjob%% *}"
    [ -n "$mjob" ] || continue
    if grep -qF -- "${mjob%%:*}" <<<"$KEPT" 2>/dev/null; then
      echo "WARNING [$acct]: an UNMANAGED line already mentions '${mjob%%:*}' -- managing it here as well would run it twice. Remove the raw line (crontab -e) or drop the conf." >&2
    fi
  done <<<"${ACCT_LINES[$acct]}"

  NEW_FILE="/tmp/sync-crontab.$$.$acct.new"
  {
    printf '%s\n' "$KEPT"
    echo "$MARK_BEGIN"
    printf '%s' "${ACCT_LINES[$acct]}"
    echo "$MARK_END"
  } > "$NEW_FILE"

  if [ "$APPLY" -eq 0 ]; then
    echo "--- preview only for $acct_label (pass --apply to actually install) ---"
    cat "$NEW_FILE"
    rm -f "$NEW_FILE"
    continue
  fi

  mkdir -p "$acct_backup_dir"
  BACKUP_FILE="$acct_backup_dir/$(date -Is).bak"
  printf '%s\n' "$CURRENT_CRONTAB" > "$BACKUP_FILE"
  echo "backed up $acct's crontab to $BACKUP_FILE"

  if [ "$acct" = "$LOCAL_ACCOUNT" ]; then
    crontab "$NEW_FILE"
  else
    # stdin, not a path: the file is owned by the invoker and unreadable
    # to the target account under a sane umask.
    sudo -n -u "$acct" crontab - < "$NEW_FILE"
  fi
  rc=$?
  rm -f "$NEW_FILE"
  if [ "$rc" -ne 0 ]; then
    echo "ERROR [$acct]: crontab install failed (rc=$rc) -- restore with: ${acct/#$LOCAL_ACCOUNT/}${acct:+sudo -n -u $acct }crontab $BACKUP_FILE" >&2
    WRITE_ERRORS=$((WRITE_ERRORS + 1))
    continue
  fi
  echo "crontab updated for $acct_label. current state:"
  read_crontab_for "$acct"
done

if [ "$WRITE_ERRORS" -gt 0 ]; then
  echo "-- $WRITE_ERRORS account(s) above were NOT written --" >&2
  exit 1
fi
[ "$ERRORS" -gt 0 ] && exit 1
exit 0
