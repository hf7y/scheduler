#!/usr/bin/env bash
# Reads every ../schedule/*.conf entry and rewrites the REAL crontab's
# scheduler-managed block to match. This is the one and only place that
# writes cron lines for scheduler-managed jobs -- lib/sweep-loop-common.sh
# itself no longer edits crontab (see its expiry block).
#
# "Registering" a project = drop a schedule/<project>.conf (see
# ../examples/schedule-entry.conf.template) and run this script.
# "Moving hours around" = edit that file's SWEEP_CRON/BATCH_CRON and
# run this script again. "Deregistering" = delete the file and run again.
#
# Safe by default: prints what it WOULD install and exits. Nothing is
# written to the real crontab unless you pass --apply.
#
# Only ever touches lines between the BEGIN/END markers below -- anything
# else already in your crontab (including any not-yet-migrated raw entry
# like chezz's original unrestricted line) is left exactly as-is. If
# you're migrating an existing raw entry onto a schedule/*.conf file,
# remove the old raw line yourself first (crontab -e) or you'll end up
# with two entries for the same job.
#
# TWO SCOPING AXES (2026-07-25). Both default to "here, as me", so every
# existing conf behaves exactly as before:
#
#   CRON_ACCOUNT="svc-vaporwave"   install this project's lines into THAT
#                                  user's crontab instead of the invoking
#                                  user's. Same managed-block discipline,
#                                  one block per account, one backup dir
#                                  per account. Requires passwordless
#                                  `sudo -u <account> crontab` (zach has
#                                  `(svc-vaporwave) NOPASSWD: ALL`).
#   CRON_HOST="mandark"            only install on that short hostname;
#                                  other hosts skip the conf entirely.
#
# CRON_HOST is what makes moving a service account to another box a
# one-field edit rather than a migration: the conf is the single source of
# truth for WHERE and AS WHOM a job runs, mirroring how
# usage-paced-runner.sh already resolves schedule/_paced.<host>.conf. To
# move svc-vaporwave's jobs to dexter, set CRON_HOST="dexter", run this on
# dexter with --apply, then re-run on mandark with --apply to retract the
# now-foreign block (an unlisted host produces an EMPTY managed block,
# which removes the lines rather than orphaning them).
#
# A foreign account's crontab is READ before it is written, exactly like
# the local one. If that read fails, the block for that account is NOT
# written and the script exits nonzero -- writing a managed block without
# first seeing the unmanaged lines would silently discard them, and would
# hide an already-installed job of the same name (double dispatch).

set -uo pipefail

SCHED_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCHEDULE_DIR="$SCHED_DIR/schedule"
BACKUP_DIR="$SCHED_DIR/.crontab-backups"
SCHEDULER_RUN="$SCHED_DIR/bin/scheduler-run"

# Which rotation file(s) does the paced dispatcher use? Two DIFFERENT
# questions, answered by two functions -- see lib/paced-conf.sh for the rule
# and for the mandark-self-dev-resurrection bug that made the split
# necessary. Sourcing is safe here in a way it deliberately is not in
# bin/usage-paced-runner.sh: this script is run by hand, and a failure to
# source it fails ONE invocation rather than all dispatch.
# shellcheck disable=SC1091
source "$SCHED_DIR/lib/paced-conf.sh"

MARK_BEGIN="# >>> scheduler-managed (generated by bin/sync-crontab.sh -- edit schedule/*.conf instead, then re-run) >>>"
MARK_END="# <<< scheduler-managed <<<"

LOCAL_ACCOUNT="$(id -un)"
SHORT_HOST="$(hostname -s)"

# Lines are bucketed per account: ACCT_LINES[acct] holds a newline-joined
# block, ACCT_ORDER preserves first-seen order so previews are stable.
declare -A ACCT_LINES=()
ACCT_ORDER=("$LOCAL_ACCOUNT")
ACCT_LINES["$LOCAL_ACCOUNT"]=""

add_managed_line() {
  # $1 = account, $2 = crontab line
  local acct="$1" line="$2"
  if [ -z "${ACCT_LINES[$acct]+set}" ]; then
    ACCT_LINES["$acct"]=""
    ACCT_ORDER+=("$acct")
  fi
  ACCT_LINES["$acct"]+="$line"$'\n'
}

home_of() {
  # Expiry state lives under the OWNING account's home, not the invoker's.
  local acct="$1" h
  if [ "$acct" = "$LOCAL_ACCOUNT" ]; then printf '%s' "$HOME"; return 0; fi
  h="$(getent passwd "$acct" | cut -d: -f6)"
  [ -n "$h" ] || return 1
  printf '%s' "$h"
}

# Read one account's current crontab. Echoes it on stdout; returns nonzero
# only when the read could not be performed at all (missing sudo rights,
# unknown user) -- an empty crontab is a successful read of nothing, which
# `crontab -l` reports as exit 1, hence the explicit no-crontab match.
read_crontab_for() {
  local acct="$1" out rc
  if [ "$acct" = "$LOCAL_ACCOUNT" ]; then
    crontab -l 2>/dev/null || true
    return 0
  fi
  out="$(sudo -n -u "$acct" crontab -l 2>&1)"; rc=$?
  if [ "$rc" -ne 0 ]; then
    case "$out" in
      *"no crontab for"*) printf '' ; return 0 ;;
      *) printf '%s' "$out" >&2 ; return 1 ;;
    esac
  fi
  printf '%s' "$out"
}

APPLY=0
ADOPT=0
ALLOW_DIRTY=0
CHECK_CLEAN_ONLY=0
for arg in "$@"; do
  case "$arg" in
    --apply) APPLY=1 ;;
    --adopt) ADOPT=1 ;;
    --allow-dirty) ALLOW_DIRTY=1 ;;
    --check-clean) CHECK_CLEAN_ONLY=1 ;;
    -h|--help)
      echo "Usage: $0 [--apply]"
      echo "  (no args)  preview the crontab this would produce"
      echo "  --apply    back up the current crontab, then actually write it"
      echo "  --adopt    drop UNMANAGED lines whose command exactly matches a line"
      echo "             this run manages -- i.e. take ownership of a job that was"
      echo "             previously hand-installed, instead of duplicating it"
      echo "  --check-clean  run ONLY the committed-config gate (see below) and exit:"
      echo "             0 = schedule/ matches HEAD, 2 = dirty/unverifiable. Writes"
      echo "             nothing, reads no crontab -- safe to call from a sweep."
      echo "  --allow-dirty  proceed with --apply even when schedule/ is dirty or"
      echo "             not verifiable against a git ref. Deliberate escape hatch;"
      echo "             it says so in the output so the override is on the record."
      exit 0
      ;;
    *) echo "unknown arg: $arg (see --help)" >&2; exit 1 ;;
  esac
done

if [ ! -d "$SCHEDULE_DIR" ]; then
  echo "no $SCHEDULE_DIR yet -- nothing to sync" >&2
  exit 0
fi

# ---- committed-config gate -------------------------------------------
# CLAUDE.md build discipline: "deploy verified against a git ref; drift
# fails loud." Until now this script would happily install cron lines
# generated from a half-saved schedule/*.conf -- config that exists in
# exactly one working tree and nowhere in history. That is the same
# dirty-tree-as-deployed-config shape that already bit this repo for real
# (2026-07-26: a usage-ceiling edit lived only in the working tree, so the
# deployed behaviour had no committed source; a9bffa2).
#
# Dirty = any tracked modification/staged change under schedule/, or any
# UNTRACKED schedule/*.conf (a conf that has never been committed at all
# is the worst case, not an exempt one). Preview mode only warns -- seeing
# what an in-progress edit would produce is the normal way to check it
# before committing. --apply refuses.
schedule_dirty_report() {
  # Prints one line per problem to stdout; returns 0 if clean, 1 if dirty,
  # 2 if the tree can't be verified against a git ref at all.
  git -C "$SCHED_DIR" rev-parse --git-dir >/dev/null 2>&1 || {
    echo "schedule/ is not inside a git repository -- nothing to verify it against"
    return 2
  }
  local out
  out="$(git -C "$SCHED_DIR" status --porcelain -- schedule 2>&1)" || {
    echo "git status failed for schedule/: $out"
    return 2
  }
  [ -n "$out" ] || return 0
  printf '%s\n' "$out"
  return 1
}

DIRTY_REPORT="$(schedule_dirty_report)"; DIRTY_RC=$?

if [ "$DIRTY_RC" -ne 0 ]; then
  {
    if [ "$DIRTY_RC" -eq 2 ]; then
      echo "UNVERIFIABLE: schedule/ cannot be checked against a git ref:"
    else
      echo "DIRTY: schedule/ does not match HEAD -- these would be deployed from an uncommitted state:"
    fi
    printf '%s\n' "$DIRTY_REPORT" | sed 's/^/    /'
  } >&2
fi

if [ "$CHECK_CLEAN_ONLY" -eq 1 ]; then
  if [ "$DIRTY_RC" -eq 0 ]; then
    echo "schedule/ is clean at $(git -C "$SCHED_DIR" rev-parse --short HEAD 2>/dev/null || echo '?')"
    exit 0
  fi
  exit 2
fi

if [ "$DIRTY_RC" -ne 0 ] && [ "$APPLY" -eq 1 ]; then
  if [ "$ALLOW_DIRTY" -eq 1 ]; then
    echo "OVERRIDE: --allow-dirty given; installing cron lines generated from the state above anyway." >&2
  else
    echo "REFUSING to --apply: commit schedule/ first (or pass --allow-dirty to override deliberately)." >&2
    exit 2
  fi
fi

# Batch config for Tier 2 auto-staggering -- see "BATCH_CRON=auto" below.
# schedule/_batch.conf is optional (leading underscore keeps it out of the
# *.conf glob every project's entry is read from, below).
BATCH_BASE_TIME="01:00"
BATCH_STAGGER_MINUTES=30
if [ -f "$SCHEDULE_DIR/_batch.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_batch.conf"
fi
BATCH_BASE_MINUTES=$(( 10#${BATCH_BASE_TIME%%:*} * 60 + 10#${BATCH_BASE_TIME##*:} ))

# $1 = slot index (0-based) -> prints "MIN HOUR" for that slot, wrapping
# past midnight if the batch runs long enough to need it.
batch_slot_time() {
  local idx="$1"
  local total=$(( (BATCH_BASE_MINUTES + idx * BATCH_STAGGER_MINUTES) % 1440 ))
  printf '%d %d' "$((total % 60))" "$((total / 60))"
}

# --- Paced-runner meta (optional) ---------------------------------------------
# schedule/_runner.conf turns on usage-paced dispatch: one frequent tick runs
# bin/usage-paced-runner.sh, which round-robins the ENABLED participants in
# THIS HOST'S rotation file (schedule/_paced.<host>.conf, else the shared
# schedule/_paced.conf) whenever usage-gate.sh reports spare weekly quota. With
# PACED_SUPPRESS_BATCH=1, any project that IS a paced participant gets its fixed
# nightly BATCH cron line suppressed below (the runner dispatches it instead) --
# each project's BATCH_* config stays intact, so deleting _runner.conf restores
# the old fixed-time behaviour on the next sync. SWEEP (bug-sweep) tiers are
# never suppressed.
#
# HOST-SCOPED SINCE 2026-07-29, and this was a live defect, not a tidy-up.
# The tick meta was read from ONE shared file while the rotation it dispatches
# has been per-host (_paced.<host>.conf) since 2026-07-24. So on dexter,
# `--apply` would have installed MANDARK's cadence:
#
#   */5 PACED_MAX_PER_TICK=16 USAGE_CEILING=0.99 usage-paced-runner.sh
#
# where dexter had been deliberately running */30 with PACED_MAX_PER_TICK=1 --
# a 6x rate increase on the host that shares one account budget with the other,
# installed silently by a command whose whole job is to make the crontab match
# the confs. That is why dexter's crontab was HAND-WRITTEN on 2026-07-24 and
# why its own header called host-scoping "an open item": the generator could
# not express what that host needed, so a human bypassed the generator. A
# config surface a host cannot use is a config surface that host routes around.
#
# Resolution is SHARED-THEN-HOST, sourced in that order, so the host file
# overrides PER FIELD and only needs to state what differs -- the same
# precedence _usage.conf documents for the pacing knobs. A host file may also
# blank a field (RUNNER_CRON="") to opt out of a tick the shared file arms;
# dexter has never run the sweep tick that _sweep.conf would install.
#
# OPT-OUT IS DETECTED BY COMPARISON, NOT BY EMPTINESS (fixed 2026-07-29 --
# the sentence above described a mechanism this script did not implement,
# and schedule/_sweep.dexter.conf was already relying on it). An empty CRON
# is ambiguous on its own: it is EITHER "this host opted out" OR "the shared
# conf is incomplete", and the emit blocks below rightly treat the second as
# a hard ERROR. So the shared file's value is captured BEFORE the host file
# is sourced, and only the transition non-empty -> empty counts as an opt-out.
# That keeps the incomplete-conf error loud (a shared file that never set a
# CRON still errors, host file or not) while letting a host turn a tick off.
RUNNER_JOB=""; RUNNER_CMD=""; RUNNER_CRON=""; RUNNER_ENV=""; PACED_SUPPRESS_BATCH=0
RUNNER_CONF_SRC="none"
RUNNER_OPTOUT=0
SYNC_HOST="${SYNC_HOST:-$(hostname -s 2>/dev/null || hostname 2>/dev/null || echo unknown)}"
if [ -f "$SCHEDULE_DIR/_runner.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_runner.conf"
  RUNNER_CONF_SRC="_runner.conf"
fi
RUNNER_CRON_SHARED="$RUNNER_CRON"
if [ -f "$SCHEDULE_DIR/_runner.$SYNC_HOST.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_runner.$SYNC_HOST.conf"
  RUNNER_CONF_SRC="${RUNNER_CONF_SRC} + _runner.$SYNC_HOST.conf (host override)"
  [ -n "$RUNNER_CRON_SHARED" ] && [ -z "$RUNNER_CRON" ] && RUNNER_OPTOUT=1
fi

# --- Sweep tick meta (optional) ------------------------------------------------
# schedule/_sweep.conf's mere presence adds ONE fixed, always-on tick for
# `scheduler sweep` -- deliberately separate from the usage-paced dispatch
# above (sweep is pure git/bash, zero API cost, so gating it behind
# usage-gate.sh would protect a budget it never touches).
#
# Host-scoped on the same shared-then-host rule as _runner.conf above, and for
# the same reason: dexter has never run this tick, and a shared-only read would
# install one there on the first --apply.
SWEEP_TICK_JOB=""; SWEEP_TICK_CMD=""; SWEEP_TICK_CRON=""
SWEEP_CONF_SRC="none"
SWEEP_OPTOUT=0
if [ -f "$SCHEDULE_DIR/_sweep.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_sweep.conf"
  SWEEP_CONF_SRC="_sweep.conf"
fi
SWEEP_TICK_CRON_SHARED="$SWEEP_TICK_CRON"
if [ -f "$SCHEDULE_DIR/_sweep.$SYNC_HOST.conf" ]; then
  # shellcheck disable=SC1091
  source "$SCHEDULE_DIR/_sweep.$SYNC_HOST.conf"
  SWEEP_CONF_SRC="${SWEEP_CONF_SRC} + _sweep.$SYNC_HOST.conf (host override)"
  # Same shared-then-host opt-out rule as the runner block above; see there
  # for why emptiness alone is not enough to tell opt-out from misconfig.
  [ -n "$SWEEP_TICK_CRON_SHARED" ] && [ -z "$SWEEP_TICK_CRON" ] && SWEEP_OPTOUT=1
fi
PACED_SET=" "          # listed in ANY host's rotation -> the runner owns Tier 2
PACED_ENABLED_SET=" "  # listed AND enabled in THIS host's rotation -> dispatches here
#
# MEMBERSHIP, not the enabled flag (fixed 2026-07-25). Being listed in a
# rotation file means the usage-paced runner owns this project's Tier 2,
# full stop. The flag says whether it currently dispatches -- parked (0)
# means "don't run it", NOT "fall back to a fixed nightly cron line".
# Reading the flag here meant parking a project silently re-armed its fixed
# BATCH line on the next --apply: caught in preview that day, where crt
# (moved to dexter) plus the four projects parked on 2026-07-24 all wanted
# nightly slots that the live crontab correctly does not have. Parking is an
# admission-control decision; a sync script must not overturn it as a side
# effect.
#
# ...and the SAME defect one level up, fixed 2026-07-29: which FILE that
# membership is read from. This block hardcoded `_paced.conf` while
# bin/usage-paced-runner.sh (and, since a7066ff, bin/scheduler) resolve
# schedule/_paced.<host>.conf. Commenting out mandark's `scheduler|1|3` line
# to make its self-dev dark (58d6495) therefore dropped `scheduler` out of
# PACED_SET -- arming an auto-staggered fixed nightly scheduler-dev-cycle.sh
# for the next --apply, on the very host that had just stopped being a writer
# of scheduler's own history, and on dexter where the rotation already
# dispatches it. Reproduced in a sandbox: `0 1 * * * .../scheduler-dev-cycle.sh
# # scheduler:scheduler:BATCH (scheduler-paced-dev, auto-batched)`.
# Membership is now the UNION across every host's rotation -- see
# lib/paced-conf.sh's paced_membership_set for why the union, and not this
# host's file, is the right (and the only monotonically safe) answer to it.
if [ "${PACED_SUPPRESS_BATCH:-0}" = "1" ]; then
  if ! paced_membership_set "$SCHED_DIR"; then
    echo "ERROR: schedule/_runner.conf sets PACED_SUPPRESS_BATCH=1, but $PACED_MEMBERS_SRC" >&2
    echo "       Suppression is decided by rotation membership, so with no rotation file at all" >&2
    echo "       this script cannot tell which projects the runner owns -- and guessing 'none'" >&2
    echo "       would install a fixed nightly cron line for EVERY project. Refusing." >&2
    exit 2
  fi
  PACED_SET="$PACED_MEMBERS"
  # Separately: is it actually DISPATCHING here, from THIS host's rotation?
  # Only an enabled entry can collide with a foreign account's crontab on
  # this machine (see the double-dispatch guard) -- that question is
  # host-local, so it reads the host-resolved file, not the union.
  if resolve_paced_conf "$SCHED_DIR"; then
    while IFS='|' read -r pname penabled _; do
      case "$pname" in ''|\#*) continue ;; esac
      [ "${penabled// /}" = "1" ] && PACED_ENABLED_SET+="${pname// /} "
    done < "$PACED_CONF"
  else
    # Reachable only when some OTHER host owns a rotation file and this one
    # has neither its own nor the shared default. Say so rather than letting
    # an empty enabled-set quietly weaken the double-dispatch guard below.
    echo "note: $PACED_CONF_SRC -- nothing is paced-dispatched on $SHORT_HOST," >&2
    echo "      so the foreign-account double-dispatch guard has nothing to check against." >&2
  fi
fi
is_paced() { case "$PACED_SET" in *" $1 "*) return 0 ;; *) return 1 ;; esac; }
is_paced_enabled() { case "$PACED_ENABLED_SET" in *" $1 "*) return 0 ;; *) return 1 ;; esac; }

