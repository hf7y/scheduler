is_expired() {
  # $1 = JOB_NAME. Mirrors the expiry check lib/sweep-loop-common.sh
  # itself does -- same file, same ISO-8601 string comparison.
  local job_name="$1" acct="${2:-$LOCAL_ACCOUNT}" acct_home
  acct_home="$(home_of "$acct")" || return 1
  local expires_at_file="$acct_home/.local/share/$job_name/expires_at"
  [ -f "$expires_at_file" ] || return 1
  local expires_at now_is
  expires_at=$(cat "$expires_at_file")
  now_is=$(date -Is)
  [[ "$now_is" > "$expires_at" ]]
}

validate_cron() {
  # $1 = cron expression. Exactly 5 whitespace-separated fields.
  local field_count
  field_count=$(awk '{print NF}' <<<"$1")
  [ "$field_count" -eq 5 ]
}

# Is the command word of a META cron line (the RUNNER tick, the SWEEP tick)
# actually runnable on THIS host? $1 = the full command string from the conf
# (e.g. "/home/zach/.local/bin/scheduler sweep"). Echoes the reason and
# returns 1 when it is not; returns 0 silently when it is.
#
# WHY THIS EXISTS (2026-07-29, found by re-probing rather than reading):
# every PER-PROJECT line already goes through resolve_cmd, which refuses a
# <TIER>_SCRIPT that is absent or non-executable. The two META tiers were the
# exception -- they validated only that the conf fields were non-empty and
# that the cron expression had 5 fields, never that the command exists. On
# dexter that gap was live: `/home/zach/.local/bin/scheduler` has never been
# installed (only usage-gate.sh and usage-paced-runner.sh are, symlinked
# 2026-07-24), so `bin/sync-crontab.sh --apply` would cheerfully install
# `*/15 * * * * /home/zach/.local/bin/scheduler sweep` -- a tick that fails
# with "command not found" every 15 minutes into a mail spool nobody reads.
# A generated crontab that is dead on arrival is the exit-0 no-op this
# project's own discipline calls worse than a crash.
#
# Same verdict as resolve_cmd's: the line is OMITTED and counted as an ERROR,
# not emitted with a warning. Install the command, then re-run.
meta_cmd_unrunnable() {
  local cmdline="$1" word
  # The command WORD -- cron lines run through `sh -c`, so this is the first
  # whitespace-separated token. Meta lines carry no leading VAR=val
  # assignments (RUNNER_ENV is prepended separately, after this check).
  word="${cmdline%%[[:space:]]*}"
  if [ -z "$word" ]; then
    echo "command string is empty"
    return 1
  fi
  case "$word" in
    */*)
      # Absolute/relative path: exact, and the case both shipped confs use.
      # -x follows symlinks, so a DANGLING symlink fails here too, which is
      # the failure mode a bare `-e` on the link would miss.
      if [ ! -x "$word" ]; then
        echo "$word does not exist or isn't executable"
        return 1
      fi
      ;;
    *)
      # Bare name: resolved against cron's PATH at run time, which is the
      # PATH= line in the crontab and not necessarily this shell's. Checked
      # on a best-effort basis, and the message says so rather than claiming
      # more certainty than it has.
      if ! command -v "$word" >/dev/null 2>&1; then
        echo "$word is not on this shell's PATH (bare name -- cron resolves it against the crontab's own PATH, so check that too)"
        return 1
      fi
      ;;
  esac
  return 0
}

# Resolve the command cron should run for one tier, honoring backwards
# compatibility. $1=tier label (SWEEP|BATCH), $2=<TIER>_SCRIPT value,
# $3=<TIER>_PROMPT value, $4=scheduler-run subcommand (sweep|batch). Echoes
# the command string on success; sets RESOLVE_ERR and returns 1 otherwise.
# Precedence: a legacy *_SCRIPT wins (proven, unchanged) -- drop it to switch
# a tier onto scheduler-run, which reads REPO_URL/<TIER>_PROMPT from the conf.
# Sets RESOLVE_OUT (the command) and RESOLVE_ERR (the reason on failure).
# Both are GLOBALS on purpose: this used to echo the command and be called
# as cmd=$(resolve_cmd ...), which runs it in a subshell, so every
# RESOLVE_ERR it set was discarded and each failure printed "ERROR
# [x/BATCH]:  -- skipping" with a blank reason (fixed 2026-07-25, found
# when aedile/vkv-inventory failed this check for an unrelated reason and
# said nothing about why).
RESOLVE_ERR=""
RESOLVE_OUT=""
resolve_cmd() {
  local tier="$1" script="$2" prompt="$3" sub="$4"
  RESOLVE_ERR=""; RESOLVE_OUT=""
  if [ -n "$script" ]; then
    # Check executability AS THE ACCOUNT THAT WILL RUN IT. Testing as the
    # invoker is wrong for a foreign-account job: the wrapper lives in that
    # account's home, so the moment those permissions are tightened to a
    # sane 0700 (svc-vaporwave's home is 0777 today, which is its own
    # problem) a perfectly valid job would fail this check for the wrong
    # reason -- and conversely, invoker-readable says nothing about whether
    # cron can run it as that user.
    local acct="${conf_account:-$LOCAL_ACCOUNT}"
    if [ "$acct" = "$LOCAL_ACCOUNT" ]; then
      if [ ! -x "$script" ]; then
        RESOLVE_ERR="${tier}_SCRIPT=$script does not exist or isn't executable"
        return 1
      fi
    elif ! sudo -n -u "$acct" test -x "$script" 2>/dev/null; then
      if [ -x "$script" ] 2>/dev/null; then
        RESOLVE_ERR="${tier}_SCRIPT=$script is executable by $LOCAL_ACCOUNT but NOT by $acct, the account that would run it"
      else
        RESOLVE_ERR="${tier}_SCRIPT=$script is not executable by $acct (checked: sudo -n -u $acct test -x)"
      fi
      return 1
    fi
    RESOLVE_OUT="$script"; return 0
  fi
  # New mode: no legacy wrapper -> run via scheduler-run from the conf.
  if [ ! -x "$SCHEDULER_RUN" ]; then
    RESOLVE_ERR="scheduler-run not found/executable at $SCHEDULER_RUN"
    return 1
  fi
  if [ -z "${REPO_URL:-}" ]; then
    RESOLVE_ERR="no ${tier}_SCRIPT and no REPO_URL set -- provide one (see examples/schedule-entry.conf.template)"
    return 1
  fi
  if [ -z "$prompt" ]; then
    RESOLVE_ERR="no ${tier}_SCRIPT and no ${tier}_PROMPT set -- provide one"
    return 1
  fi
  RESOLVE_OUT="$SCHEDULER_RUN $PROJECT $sub"; return 0
}

